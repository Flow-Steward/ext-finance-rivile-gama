def is_paged(spec: dict[str, Any]) -> bool:
    return any(p["name"].lower() == "pagenumber" for p in spec["params"])


def param_rows(spec: dict[str, Any]) -> list[dict[str, Any]]:
    required_extra = REQUIRED_PARAMS.get(spec["method"], set())
    rows: list[dict[str, Any]] = []
    seen: set[str] = set()
    data_roots = set(spec["data_roots"])
    for param in spec["params"]:
        wire = param["name"]
        if wire in data_roots:
            continue
        key = wire.lower()
        if key in seen:
            continue
        seen.add(key)
        name = snake(wire)
        rows.append(
            {
                "wire": wire,
                "name": name,
                "description": clean(param.get("description", ""), 600),
                "options": [o["value"] for o in param.get("options", [])],
                "option_labels": {
                    o["value"]: clean(o["label"], 120) for o in param.get("options", [])
                },
                "required": bool(param.get("required")) or wire in required_extra,
                "list_values": list(spec.get("list_values") or []),
            }
        )
    return rows


def method_rows() -> list[dict[str, Any]]:
    spec = json.loads(SPEC_PATH.read_text(encoding="utf-8"))
    rows = []
    for item in spec:
        method = item["method"]
        if method not in TITLES:
            raise SystemExit(f"missing English title for {method}")
        write = item["kind"] != "read" or method in WRITE_OVERRIDES
        roots = {
            root: {
                "fields": list(value.get("fields", [])),
                "is_list": bool(value.get("is_list")),
                "children": value.get("children", {}),
                "description": clean(value.get("description", ""), 200),
            }
            for root, value in item["data_roots"].items()
        }
        rows.append(
            {
                "method": method,
                "operation_id": method.lower(),
                "write": write,
                "title": TITLES[method],
                "group": group_of(method),
                "lt_description": clean(item["description"], 700),
                "page": item["page"],
                "params": param_rows(item),
                "data_roots": roots,
                "paged": is_paged(item),
                "response_roots": item["response_roots"],
                "examples": item["examples"],
            }
        )
    rows.sort(key=lambda r: r["method"])
    return rows


def example_values(row: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """First example value of every documented data field, by root."""
    found: dict[str, dict[str, Any]] = {}

    def walk(root: str, value: Any) -> None:
        items = value if isinstance(value, list) else [value]
        for item in items:
            if not isinstance(item, dict):
                continue
            bucket = found.setdefault(root, {})
            for key, sub in item.items():
                if isinstance(sub, (dict, list)) and any(
                    isinstance(x, dict) for x in (sub if isinstance(sub, list) else [sub])
                ):
                    walk(key, sub)
                elif key not in bucket and isinstance(sub, (str, int, float, bool)):
                    bucket[key] = sub

    for example in row["examples"]:
        data = example.get("data") if isinstance(example, dict) else None
        if isinstance(data, dict):
            for root, value in data.items():
                walk(root, value)
    return found


