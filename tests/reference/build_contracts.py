def connection_input() -> dict[str, Any]:
    return {"name": "connection_ref", "value_type": "connection_ref", "required": True}


def param_input(row: dict[str, Any], param: dict[str, Any]) -> dict[str, Any]:
    wire, name = param["wire"], param["name"]
    lower = wire.lower()
    schema: dict[str, Any]
    value_type = "text"
    description = param["description"]
    if lower == "oper":
        values = param["options"] or ["I", "U", "D"]
        schema = {"type": "string", "enum": values}
        description = "; ".join(OPER_LABELS.get(v, v) for v in values) + ". Default I."
    elif lower == "erroraction":
        schema = {"type": "string", "enum": ERROR_ACTION_VALUES}
        description = ERROR_ACTION_HELP
    elif (row["method"], wire) in PARAM_ENUMS:
        schema = {"type": "string", "enum": PARAM_ENUMS[(row["method"], wire)]}
    elif lower == "list" and row["method"] != "GET_PRICES_TIME":
        schema = {"type": "string", "enum": param["list_values"] or ["H", "A"]}
        description = description or LIST_HELP
    elif lower == "pagenumber":
        value_type = "integer"
        schema = {"type": "integer", "minimum": 1, "maximum": 1000000}
        description = PAGE_HELP
    elif lower in {"show_doc", "overwrite"}:
        value_type = "integer"
        schema = {"type": "integer", "enum": [0, 1]}
        if lower == "show_doc" and row["method"] in SHOW_DOC_DEFAULT_ZERO:
            description = (
                "1 — return the files' Base64 content (DOC) in the result; 0 — do not. "
                "This extension sends 0 unless you set 1; to download a file use "
                "get_i06_doc, which saves it as a workflow file."
            )
    elif lower == "fil":
        schema = {"type": "string", "maxLength": 8000}
        description = FIL_HELP
    elif lower == "doc":
        schema = {"type": "string", "maxLength": 30 * 1024 * 1024}
        description = (
            "The file content, Base64-encoded. Leave empty when document_file supplies the file."
        )
    elif lower == "pap_xml" or lower == "papxml":
        schema = {"type": "string", "maxLength": 200000}
    else:
        schema = {"type": "string", "maxLength": 4000}
    schema["title"] = f"{wire}"
    if description:
        schema["description"] = clean(description, 600)
    return {
        "name": name,
        "value_type": value_type,
        "required": bool(param["required"]),
        "schema": schema,
    }


def field_registry() -> dict[str, dict[str, dict[str, str]]]:
    """Field tables of every page by table tag; EDIT pages first, they carry the EDIT notes."""
    spec = json.loads(SPEC_PATH.read_text(encoding="utf-8"))
    ordered = sorted(spec, key=lambda m: (0 if "EDIT_" in m["method"] else 1, m["method"]))
    registry: dict[str, dict[str, dict[str, str]]] = {}
    for item in ordered:
        for tag, rows in (item.get("field_tables") or {}).items():
            bucket = registry.setdefault(tag.upper(), {})
            for row in rows:
                bucket.setdefault(row["name"], row)
    return registry


FIELDS = field_registry()


def field_description(table: str, field: str) -> str:
    row = FIELDS.get(table.upper(), {}).get(field)
    if not row:
        return ""
    parts = [row.get("type", ""), row.get("description", "")]
    text = " — ".join(p for p in parts if p)
    if row.get("notes"):
        text = f"{text}. EDIT: {row['notes']}"
    return clean(text, 400)


def table_fields(table: str, fields: list[str]) -> list[str]:
    merged = list(fields)
    for name in FIELDS.get(table.upper(), {}):
        if name not in merged:
            merged.append(name)
    return merged


def root_schema(
    root: str, meta: dict[str, Any], values: dict[str, dict[str, Any]]
) -> dict[str, Any]:
    def props(table: str, fields: list[str]) -> dict[str, Any]:
        out: dict[str, Any] = {}
        for field in table_fields(table, fields):
            entry: dict[str, Any] = {"title": field}
            description = field_description(table, field)
            if description:
                entry["description"] = description
            example = values.get(table, {}).get(field)
            if example is not None:
                entry["examples"] = [example]
            out[field] = entry
        return out

    properties = props(root, meta["fields"])
    for child, child_meta in (meta.get("children") or {}).items():
        properties[child] = {
            "type": ["array", "object"],
            "title": f"{child} lines",
            "description": f"{child} detail lines: a list of objects (or one object).",
            "items": {
                "type": "object",
                "additionalProperties": True,
                "properties": props(child, child_meta.get("fields", [])),
            },
            "additionalProperties": True,
            "properties": props(child, child_meta.get("fields", [])),
        }
    description = meta.get("description") or f"{root} record"
    if meta.get("is_list"):
        return {
            "type": ["object", "array"],
            "title": root,
            "description": clean(f"{description}. One object or a list of objects.", 300),
            "additionalProperties": True,
            "properties": properties,
            "items": {"type": "object", "additionalProperties": True, "properties": properties},
        }
    # Rivile writes one record per request (naudojimo pagrindai §1.1).
    return {
        "type": "object",
        "title": root,
        "description": clean(f"{description}. One record per request.", 300),
        "additionalProperties": True,
        "properties": properties,
    }


def data_input(row: dict[str, Any]) -> dict[str, Any] | None:
    roots = row["data_roots"]
    if not roots:
        return None
    values = example_values(row)
    names = ", ".join(roots)
    return {
        "name": "data",
        "value_type": "object",
        "required": row["write"],
        "schema": {
            "type": "object",
            "title": "Data",
            "description": clean(
                f"The Rivile data block: {names}. Field names are Rivile's own (for example "
                f"{next(iter(roots))}_...). Extra fields PAP_1, PAP_2… and dimensions are passed "
                "through unchanged.",
                400,
            ),
            "additionalProperties": True,
            "properties": {root: root_schema(root, meta, values) for root, meta in roots.items()},
        },
    }


