# Naming


def snake(name: str) -> str:
    """Rivile wire name -> input name (``errorAction`` -> ``error_action``)."""
    if name.lower() == "pagenumber":
        return "page_number"
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    text = re.sub(r"[^A-Za-z0-9]+", "_", text).strip("_").lower()
    if text == "papxml":
        return "pap_xml"
    return text


def group_of(method: str) -> str:
    code = re.sub(r"^(MGAMA_)?(GET|EDIT)_", "", method)
    code = code.replace("_LIST_EXT", "").replace("_LIST_TIME", "").replace("_LIST", "")
    for prefix, group in GROUPS:
        if code.startswith(prefix) and (len(prefix) > 1 or code[:1] == "A"):
            if prefix == "A" and not re.fullmatch(r"A\d\d.*", code):
                continue
            return group
    return DEFAULT_GROUP


def clean(text: str, limit: int = 900) -> str:
    out = " ".join(str(text or "").replace("`", "").split())
    return out if len(out) <= limit else out[: limit - 1].rstrip() + "…"


