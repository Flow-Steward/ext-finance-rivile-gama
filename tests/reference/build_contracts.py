def runtime_registry(rows: list[dict[str, Any]]) -> str:
    lines = [
        '"""Closed registry of every Rivile GAMA API v2 method this bundle exposes.',
        "",
        "Generated by tests/reference/build_contracts.py — do not edit by hand.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from .models import Method",
        "",
        "METHODS: tuple[Method, ...] = (",
    ]
    for r in rows:
        params = ", ".join(f"({p['name']!r}, {p['wire']!r})" for p in r["params"])
        roots = ", ".join(repr(k) for k in r["data_roots"])
        req = [p["name"] for p in r["params"] if p["required"]]
        required = ", ".join(repr(n) for n in req)
        lines.append(
            "    Method("
            f"method={r['method']!r}, write={r['write']!r}, paged={r['paged']!r}, "
            f"params=({params}{',' if len(r['params']) == 1 else ''}), "
            f"data_roots=({roots}{',' if len(r['data_roots']) == 1 else ''}), "
            f"title={r['title']!r}, group={r['group']!r}, "
            f"required=({required}{',' if len(req) == 1 else ''})),"
        )
    lines.append(")")
    lines.append("")
    return "\n".join(lines)


def reference_page(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """The API Reference page: every operation, grouped as in the Rivile guide."""
    groups: dict[str, list[dict[str, Any]]] = {}
    for row in rows:
        groups.setdefault(row["group"], []).append(row)
    start = ["| Operation | What it does | |", "|---|---|---|"]
    for spec in friendly_contracts.operations():
        mark = "✎" if spec["kind"] == "action" else ""
        start.append(f"| **{spec['display_name']}** | {spec['description']} | {mark} |")
    components: list[dict[str, Any]] = [
        {
            "component_id": "reference_start_here",
            "type": "markdown",
            "title": "Start here",
            "body": (
                "Everyday tasks in plain terms — each step makes the Rivile calls it needs. "
                "The raw Rivile methods follow below and appear in the step picker as "
                "**Advanced · …**.\n\n" + "\n".join(start) + "\n"
            ),
        },
        {
            "component_id": "reference_intro",
            "type": "markdown",
            "title": "Every Rivile GAMA API v2 method",
            "body": (
                f"This release covers all {len(rows)} methods of the Rivile GAMA API v2 guide "
                f"({sum(1 for r in rows if not r['write'])} read, "
                f"{sum(1 for r in rows if r['write'])} write), plus **Test the connection**, "
                "**Call any Rivile method** and **Export a Rivile list to a JSONL file**. "
                "Writes are marked ✎. Each method links to its page in the Rivile guide."
            ),
        },
    ]
    for index, group in enumerate(sorted(groups)):
        lines = ["| Operation | Rivile method | |", "|---|---|---|"]
        for row in sorted(groups[group], key=lambda r: (r["title"], r["method"])):
            mark = "✎" if row["write"] else ""
            lines.append(
                f"| {row['title']} | [{row['method']}]({DOCS_BASE}{row['page']}) | {mark} |"
            )
        components.append(
            {
                "component_id": f"reference_group_{index + 1}",
                "type": "markdown",
                "title": group,
                "body": "\n".join(lines) + "\n",
            }
        )
    return {
        "page_id": "api-reference",
        "title": "API Reference",
        "description": "Every Rivile GAMA method this extension exposes, grouped by area.",
        "components": components,
    }


def dump(path: Path, payload: Any) -> None:
    text = yaml.safe_dump(payload, sort_keys=False, allow_unicode=True, width=100)
    path.write_text(GENERATED_HEADER + text, encoding="utf-8")


def splice_effects(effects: list[dict[str, Any]]) -> None:
    """Replace ``external_effects`` in extension.yaml, keeping every other key and its order.

    The manifest is also rewritten by ``extensions lock-deps``, so it is edited as
    data rather than by text markers.
    """
    manifest = ROOT / "extension.yaml"
    data = yaml.safe_load(manifest.read_text(encoding="utf-8"))
    rebuilt: dict[str, Any] = {}
    for key, value in data.items():
        if key == "runtime" and "external_effects" not in rebuilt:
            rebuilt["external_effects"] = effects
        if key != "external_effects":
            rebuilt[key] = value
    rebuilt.setdefault("external_effects", effects)
    manifest.write_text(
        yaml.safe_dump(rebuilt, sort_keys=False, allow_unicode=True, width=100), encoding="utf-8"
    )


def outputs() -> dict[str, Any]:
    rows = method_rows()
