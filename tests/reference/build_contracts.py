def action_for(op: dict[str, Any]) -> dict[str, Any]:
    write = op["operation_kind"] == "action"
    action: dict[str, Any] = {
        "action_id": op["operation_id"],
        "title": op["display_name"],
        "description": op["description"],
        "required_scopes": ["extension:invoke"],
        "handler": {"mode": "extension"},
    }
    if write:
        action["command_type"] = "invoke_extension_action"
    action["mutates_platform"] = write
    action["workflow_visible"] = True
    action["parameters"] = [
        {
            "name": i["name"],
            "type": ACTION_PARAM_TYPES[i["value_type"]],
            "required": bool(i.get("required")),
        }
        for i in op["inputs"]
    ]
    action["result_fields"] = [o["name"] for o in op["outputs"]]
    action["error_codes"] = list(op["error_codes"])
    return action


def widget_for(item: dict[str, Any]) -> str:
    schema = item.get("schema") or {}
    if schema.get("enum"):
        return "select"
    vt = item["value_type"]
    if vt in {"object", "array", "json"}:
        return "json"
    if vt == "boolean":
        return "boolean"
    if vt in {"integer", "number"}:
        return "number"
    if item["name"] in {"fil", "doc", "pap_xml"}:
        return "textarea"
    return "text"


def form_for(op: dict[str, Any]) -> dict[str, Any]:
    fields = []
    for item in op["inputs"]:
        if item["value_type"] in {"connection_ref", "artifact_handle"}:
            continue
        schema = item.get("schema") or {}
        field: dict[str, Any] = {
            "name": item["name"],
            "label": schema.get("title") or item["name"],
            "widget_type": widget_for(item),
            "required": bool(item.get("required")),
        }
        if schema.get("description"):
            field["help_text"] = clean(schema["description"], 400)
        if schema.get("enum"):
            field["options"] = [{"label": str(v), "value": v} for v in schema["enum"]]
        fields.append(field)
    return {"operation_id": op["operation_id"], "title": op["display_name"], "fields": fields}


