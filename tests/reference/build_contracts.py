def method_operation(row: dict[str, Any]) -> dict[str, Any]:
    inputs: list[dict[str, Any]] = [connection_input()]
    inputs += [param_input(row, p) for p in row["params"]]
    data = data_input(row)
    if data is not None:
        inputs.append(data)
    if row["paged"]:
        inputs += paging_inputs()
    files = False
    if row["method"] in UPLOAD_METHODS:
        inputs.append(upload_input())
        files = True
    if row["method"] in DOWNLOAD_METHODS:
        inputs.append(download_input())
        files = True
    inputs.append(extra_params_input())
    names = [i["name"] for i in inputs]
    if len(names) != len(set(names)):
        raise SystemExit(f"duplicate input names for {row['method']}: {names}")
    outputs = common_outputs(row, write=row["write"])
    description = (
        f"Rivile GAMA {row['method']} — {row['title']}. Rivile: {row['lt_description']} "
        f"Docs: {DOCS_BASE}{row['page']}"
    )
    op: dict[str, Any] = {
        "operation_id": row["operation_id"],
        "display_name": f"{ADVANCED_PREFIX}{row['title']} ({row['method']})",
        "description": clean(description, 1000),
        "operation_kind": "action" if row["write"] else "source",
        "category": CATEGORY,
        "connection_type_ids": [CONNECTION_TYPE_ID],
        "workflow_visible": True,
    }
    if row["write"]:
        op["effect_kind"] = effect_kind(row["operation_id"])
    op["inputs"] = inputs
    op["outputs"] = outputs
    op["result_fields"] = [f"result.{o['name']}" for o in outputs]
    op["error_codes"] = errors_for(row, write=row["write"], files=files)
    return op


def effect_kind(operation_id: str) -> str:
    return f"rivile_{operation_id}"


